// Puente juego → GMAT: un script real por órbita. La física la calcula GMAT, aquí solo se escribe el script.
import { PLANET } from './data/planet'

export const MOON_R_KM = 1737.4

/** Elementos keplerianos (Luna, ejes inerciales del cuerpo) de cada órbita del catálogo. */
export const ORBIT_ELEMENTS: Record<string, { sma: number; ecc: number; aop: number }> = {
  polar_low: { sma: MOON_R_KM + 50, ecc: 0.001, aop: 270 },
  polar_high: { sma: MOON_R_KM + 100, ecc: 0.001, aop: 270 },
  // 100 × 3,000 km con el periapsis sobre el polo sur (AOP 270° en una órbita polar).
  polar_ellip: { sma: MOON_R_KM + 1550, ecc: 2900 / (2 * (MOON_R_KM + 1550)), aop: 270 },
}

export const MARS_R_KM = 3396.19

/** Marte: las mismas tres órbitas con altitudes de misiones reales (MRO, Mars Odyssey, Mars Express). */
export const MARS_ORBIT_ELEMENTS: Record<string, { sma: number; ecc: number; aop: number }> = {
  polar_low: { sma: MARS_R_KM + 250, ecc: 0.001, aop: 270 },
  polar_high: { sma: MARS_R_KM + 400, ecc: 0.001, aop: 270 },
  // 300 × 10,000 km.
  polar_ellip: { sma: MARS_R_KM + 5150, ecc: 9700 / (2 * (MARS_R_KM + 5150)), aop: 270 },
}

/** Elementos y radio del cuerpo del planeta activo (PLANET en data/planet.ts). */
export const orbitElements = (orbitId: string) => (PLANET.id === 'mars' ? MARS_ORBIT_ELEMENTS : ORBIT_ELEMENTS)[orbitId] ?? ORBIT_ELEMENTS.polar_high
export const bodyRadiusKm = () => (PLANET.id === 'mars' ? MARS_R_KM : MOON_R_KM)

export function gmatScript(orbitId: string, orbitName: string, dryMassKg = 500, days = 3): { name: string; text: string } {
  if (PLANET.id === 'mars') return marsScript(orbitId, orbitName, dryMassKg, days)
  const e = ORBIT_ELEMENTS[orbitId]
  const text = `%General Mission Analysis Tool(GMAT) Script
% Mission Architect · Selene orbiter · ${orbitName}
% Generated by the game. Lunar 10x10 gravity (LP165P) + Earth and Sun point masses.

Create Spacecraft Selene;
Selene.DateFormat = UTCGregorian;
Selene.Epoch = '01 Jul 2027 00:00:00.000';
Selene.CoordinateSystem = MoonInertial;
Selene.DisplayStateType = Keplerian;
Selene.SMA = ${e.sma.toFixed(3)};
Selene.ECC = ${e.ecc.toFixed(6)};
Selene.INC = 90;
Selene.RAAN = 0;
Selene.AOP = ${e.aop};
Selene.TA = 0;
Selene.DryMass = ${Math.round(dryMassKg)};

Create CoordinateSystem MoonInertial;
MoonInertial.Origin = Luna;
MoonInertial.Axes = BodyInertial;

Create ForceModel MoonFM;
MoonFM.CentralBody = Luna;
MoonFM.PrimaryBodies = {Luna};
MoonFM.PointMasses = {Earth, Sun};
MoonFM.GravityField.Luna.Degree = 10;
MoonFM.GravityField.Luna.Order = 10;
MoonFM.GravityField.Luna.PotentialFile = 'LP165P.cof';

Create Propagator MoonProp;
MoonProp.FM = MoonFM;
MoonProp.Type = RungeKutta89;
MoonProp.InitialStepSize = 60;
MoonProp.Accuracy = 1e-11;
MoonProp.MinStep = 0.001;
MoonProp.MaxStep = 300;

Create ReportFile SeleneReport;
SeleneReport.Filename = 'SeleneReport.txt';
SeleneReport.WriteHeaders = true;
SeleneReport.Add = {Selene.ElapsedDays, Selene.Luna.Altitude, Selene.Luna.Latitude, Selene.Luna.Longitude, Selene.MoonInertial.SMA, Selene.MoonInertial.ECC, Selene.MoonInertial.INC};

BeginMissionSequence;
Propagate MoonProp(Selene) {Selene.ElapsedDays = ${days}};
`
  return { name: `selene_${orbitId}.script`, text }
}

/** Orbitador Ares alrededor de Marte: gravedad 10×10 (Mars50c) + el Sol como masa puntual. */
function marsScript(orbitId: string, orbitName: string, dryMassKg: number, days: number): { name: string; text: string } {
  const e = MARS_ORBIT_ELEMENTS[orbitId] ?? MARS_ORBIT_ELEMENTS.polar_high
  const text = `%General Mission Analysis Tool(GMAT) Script
% Mission Architect · Ares orbiter · ${orbitName}
% Generated by the game. Mars 10x10 gravity (Mars50c) + Sun point mass.

Create Spacecraft Ares;
Ares.DateFormat = UTCGregorian;
Ares.Epoch = '01 Jul 2027 00:00:00.000';
Ares.CoordinateSystem = MarsInertial;
Ares.DisplayStateType = Keplerian;
Ares.SMA = ${e.sma.toFixed(3)};
Ares.ECC = ${e.ecc.toFixed(6)};
Ares.INC = 92.6;
Ares.RAAN = 0;
Ares.AOP = ${e.aop};
Ares.TA = 0;
Ares.DryMass = ${Math.round(dryMassKg)};

Create CoordinateSystem MarsInertial;
MarsInertial.Origin = Mars;
MarsInertial.Axes = BodyInertial;

Create ForceModel MarsFM;
MarsFM.CentralBody = Mars;
MarsFM.PrimaryBodies = {Mars};
MarsFM.PointMasses = {Sun};
MarsFM.GravityField.Mars.Degree = 10;
MarsFM.GravityField.Mars.Order = 10;
MarsFM.GravityField.Mars.PotentialFile = 'Mars50c.cof';

Create Propagator MarsProp;
MarsProp.FM = MarsFM;
MarsProp.Type = RungeKutta89;
MarsProp.InitialStepSize = 60;
MarsProp.Accuracy = 1e-11;
MarsProp.MinStep = 0.001;
MarsProp.MaxStep = 300;

Create ReportFile AresReport;
AresReport.Filename = 'AresReport.txt';
AresReport.WriteHeaders = true;
AresReport.Add = {Ares.ElapsedDays, Ares.Mars.Altitude, Ares.Mars.Latitude, Ares.Mars.Longitude, Ares.MarsInertial.SMA, Ares.MarsInertial.ECC, Ares.MarsInertial.INC};

BeginMissionSequence;
Propagate MarsProp(Ares) {Ares.ElapsedDays = ${days}};
`
  return { name: `ares_${orbitId}.script`, text }
}
